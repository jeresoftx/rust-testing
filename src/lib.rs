//! Modelos educativos para el curso `rust-testing`.
//!
//! Este crate empieza deliberadamente pequeño. Cada módulo público aparecerá
//! cuando su capítulo tenga issue, explicación, pruebas y revisión humana
//! diferida conforme a RFC-0001 §13 y §14.
//!
//! El objetivo del curso no es coleccionar frameworks de testing. El objetivo
//! es aprender a diseñar sistemas observables, verificables y mantenibles.

pub mod contract_testing;
pub mod fundamentals;
pub mod integration_tests;
pub mod mutation_testing;
pub mod performance_testing;
pub mod property_testing;
pub mod test_doubles;
pub mod unit_tests;
